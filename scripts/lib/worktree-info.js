'use strict';

/*
 * worktree-info.js — git worktree topology and cross-worktree change overlap.
 *
 * Shared by the parallel-session tooling (scripts/worktree.js, the
 * pre:edit:worktree-boundary hook, the push-time branch-name guard and
 * session-start). "Who is touching what" is always DERIVED from git, never
 * declared in a registry — a registry goes stale, git does not.
 *
 * Topology (describe / listWorktrees / currentBranch) is fs-only, so
 * PreToolUse hooks can call it without spawning git. changedFiles() does spawn
 * git and is bounded by a timeout. Nothing here throws: unreadable state
 * degrades to null / [] so callers can fail open (CLAUDE.md §7).
 *
 * Node built-ins only.
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const GIT_TIMEOUT_MS = 4000;

// Files every asset addition touches. Two open branches editing one of these
// is the usual merge-time conflict (iotpf-git-workflow §4.1/§4.2) — land such
// branches one at a time.
const REGISTRATION_POINTS = [
  '.claude/settings.json',
  '.claude/rules/iotpf-agents-skills.md',
  'scripts/hooks/bash-hook-dispatcher.js',
  'scripts/self-heal.js',
  'docs/agent-model-changelog.md',
  'docs/agent-model-master-spec.md',
  'CLAUDE.md',
  '.gitlab-ci.yml',
  '.gitattributes',
  '.gitignore',
];

// Generated views: never hand-merged, regenerated by self-heal after a sync.
const GENERATED_FILES = ['docs/asset-inventory.md', 'MISTAKES.md'];

function readTrim(file) {
  try {
    return fs.readFileSync(file, 'utf8').trim();
  } catch {
    return null;
  }
}

/** Canonical comparable form: real path, forward slashes, lowercased on Windows. */
function normalize(p) {
  const unix = realpathLenient(path.resolve(String(p || ''))).replace(/\\/g, '/').replace(/\/+$/, '');
  return process.platform === 'win32' ? unix.toLowerCase() : unix;
}

/**
 * realpath that also works for a file about to be created: resolve the
 * nearest existing ancestor (so a junction, symlink or 8.3 short name in the
 * path is still canonicalized) and re-append the part that does not exist yet.
 */
function realpathLenient(resolved) {
  const missing = [];
  let dir = resolved;
  for (;;) {
    try {
      return path.join(fs.realpathSync.native(dir), ...missing);
    } catch {
      const parent = path.dirname(dir);
      if (parent === dir) return resolved;
      missing.unshift(path.basename(dir));
      dir = parent;
    }
  }
}

function isInside(child, parent) {
  const c = normalize(child);
  const p = normalize(parent);
  return c === p || c.startsWith(`${p}/`);
}

/** Walk up from startDir to the nearest directory holding a `.git` entry. */
function findRepoRoot(startDir) {
  let dir = path.resolve(startDir || process.cwd());
  for (;;) {
    if (fs.existsSync(path.join(dir, '.git'))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/**
 * Describe the checkout containing startDir.
 * In a linked worktree `.git` is a FILE ("gitdir: <main>/.git/worktrees/<n>")
 * and <gitdir>/commondir points back at the shared git dir.
 * @returns {{root, gitDir, commonDir, mainRoot, isLinked}|null}
 */
function describe(startDir) {
  const root = findRepoRoot(startDir);
  if (!root) return null;
  const dotGit = path.join(root, '.git');
  let stat;
  try {
    stat = fs.statSync(dotGit);
  } catch {
    return null;
  }
  if (stat.isDirectory()) {
    return { root, gitDir: dotGit, commonDir: dotGit, mainRoot: root, isLinked: false };
  }
  const pointer = (readTrim(dotGit) || '').match(/^gitdir:\s*(.+)$/m);
  if (!pointer) return null;
  const gitDir = path.resolve(root, pointer[1].trim());
  const commonRel = readTrim(path.join(gitDir, 'commondir'));
  if (!commonRel) {
    // A submodule-style gitfile, not a linked worktree.
    return { root, gitDir, commonDir: gitDir, mainRoot: root, isLinked: false };
  }
  const commonDir = path.resolve(gitDir, commonRel);
  return { root, gitDir, commonDir, mainRoot: path.dirname(commonDir), isLinked: true };
}

/** Branch checked out in the described worktree, or null when detached. */
function currentBranch(info) {
  if (!info) return null;
  const head = readTrim(path.join(info.gitDir, 'HEAD')) || '';
  const m = head.match(/^ref:\s*refs\/heads\/(.+)$/);
  return m ? m[1] : null;
}

/** True when refs/heads/<name> exists in this repository (loose or packed). */
function hasLocalBranch(info, name) {
  if (!info || !name) return false;
  const ref = `refs/heads/${name}`;
  if (fs.existsSync(path.join(info.commonDir, ...ref.split('/')))) return true;
  const packed = readTrim(path.join(info.commonDir, 'packed-refs')) || '';
  return packed.split('\n').some(line => line.trim().endsWith(` ${ref}`));
}

/** Main checkout plus every linked worktree that still exists on disk. */
function listWorktrees(info) {
  if (!info) return [];
  const mainGit = info.commonDir;
  const out = [
    { root: info.mainRoot, name: '(main checkout)', isMain: true, gitDir: mainGit },
  ];
  let names = [];
  try {
    names = fs.readdirSync(path.join(mainGit, 'worktrees'));
  } catch {
    return out;
  }
  for (const name of names) {
    const gitDir = path.join(mainGit, 'worktrees', name);
    const gitFile = readTrim(path.join(gitDir, 'gitdir'));
    if (!gitFile) continue;
    const root = path.dirname(path.resolve(gitDir, gitFile));
    if (!fs.existsSync(root)) continue; // stale entry awaiting `git worktree prune`
    out.push({ root, name, isMain: false, gitDir });
  }
  return out.map(w => ({ ...w, branch: currentBranch({ gitDir: w.gitDir }) }));
}

/** The worktree that owns filePath: the DEEPEST root containing it, or null. */
function ownerOf(filePath, worktrees) {
  let best = null;
  for (const w of worktrees) {
    if (!isInside(filePath, w.root)) continue;
    if (!best || normalize(w.root).length > normalize(best.root).length) best = w;
  }
  return best;
}

/**
 * Every checkout a session can legitimately call its own: the one
 * CLAUDE_PROJECT_DIR points at and the one cwd is in. They differ when the
 * harness keeps CLAUDE_PROJECT_DIR on the main checkout for a worktree
 * session, or when a Bash `cd` moved the session — a blocking hook must
 * accept both rather than guess (fail open).
 */
function sessionCheckouts(env = process.env, cwd = process.cwd()) {
  const seen = new Set();
  const out = [];
  for (const dir of [env.CLAUDE_PROJECT_DIR, cwd]) {
    const info = dir ? describe(dir) : null;
    if (!info || seen.has(normalize(info.root))) continue;
    seen.add(normalize(info.root));
    out.push(info);
  }
  return out;
}

/**
 * The single worktree to REPORT for a session (session-start context):
 * a linked worktree wins over the main checkout.
 */
function sessionWorktree(env = process.env, cwd = process.cwd()) {
  const candidates = sessionCheckouts(env, cwd);
  return candidates.find(c => c.isLinked) || candidates[0] || null;
}

function git(root, args) {
  try {
    // quotepath off: non-ASCII (e.g. Japanese) file names come back verbatim.
    return execFileSync('git', ['-c', 'core.quotepath=false', ...args], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: GIT_TIMEOUT_MS,
      windowsHide: true,
    });
  } catch {
    return null;
  }
}

/** First of origin/main, main that resolves in this repo. */
function baseRef(root) {
  for (const ref of ['origin/main', 'main']) {
    if (git(root, ['rev-parse', '--verify', '--quiet', `${ref}^{commit}`])) return ref;
  }
  return null;
}

/**
 * Repo-relative paths a worktree has changed against the trunk: committed on
 * its branch since the merge base, plus uncommitted and untracked work.
 */
function changedFiles(root, base = baseRef(root)) {
  const files = new Set();
  if (base) {
    const committed = git(root, ['diff', '--name-only', `${base}...HEAD`]);
    for (const f of (committed || '').split('\n')) if (f.trim()) files.add(f.trim());
  }
  const status = git(root, ['status', '--porcelain', '--untracked-files=all']);
  for (const line of (status || '').split('\n')) {
    if (line.length < 4) continue;
    const entry = line.slice(3).split(' -> ').pop().trim().replace(/^"|"$/g, '');
    if (entry) files.add(entry);
  }
  return [...files].sort();
}

/**
 * Files changed in more than one worktree. Generated views are reported apart
 * because they are regenerated, not merged.
 * @param {Array<{name: string, files: string[]}>} entries
 */
function findOverlaps(entries) {
  const byFile = new Map();
  for (const e of entries) {
    for (const f of e.files) {
      if (!byFile.has(f)) byFile.set(f, []);
      byFile.get(f).push(e.name);
    }
  }
  const overlaps = [];
  const generated = [];
  for (const [file, names] of byFile) {
    if (names.length < 2) continue;
    (GENERATED_FILES.includes(file) ? generated : overlaps).push({ file, worktrees: names });
  }
  const byName = (a, b) => a.file.localeCompare(b.file);
  return { overlaps: overlaps.sort(byName), generated: generated.sort(byName) };
}

