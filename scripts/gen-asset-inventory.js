#!/usr/bin/env node
'use strict';

/*
 * gen-asset-inventory.js — single source of truth for asset counts.
 *
 * Computes the canonical inventory (agents / commands / skills / hook scripts /
 * wired hooks / rules) directly from the repo and writes docs/asset-inventory.md.
 * Docs, slides, and READMEs cite THIS file instead of hand-typed numbers, so a
 * drift like "45 agents" in a deck is caught instead of shipped.
 *
 * Usage:
 *   node scripts/gen-asset-inventory.js          # (re)generate the file
 *   node scripts/gen-asset-inventory.js --check   # CI: fail if file is stale
 *
 * Node built-ins only. --check exits 1 on drift; generate exits 0.
 */

const fs = require('fs');
const path = require('path');

const ROOT = process.env.CLAUDE_PROJECT_DIR || process.cwd();
const CLAUDE = path.join(ROOT, '.claude');
const OUT = path.join(ROOT, 'docs', 'asset-inventory.md');

function ls(dir, pred) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(pred);
}
function isDir(p) {
  return fs.existsSync(p) && fs.statSync(p).isDirectory();
}

const agents = ls(path.join(CLAUDE, 'agents'), (f) => f.endsWith('.md')).length;
const commands = ls(path.join(CLAUDE, 'commands'), (f) => f.endsWith('.md')).length;
const skills = ls(path.join(CLAUDE, 'skills'), (d) =>
  fs.existsSync(path.join(CLAUDE, 'skills', d, 'SKILL.md'))
).length;
const hookScripts = ls(path.join(ROOT, 'scripts', 'hooks'), (f) => f.endsWith('.js')).length;

let wired = 0;
const settings = path.join(CLAUDE, 'settings.json');
if (fs.existsSync(settings)) {
  const ids = new Set();
  for (const m of fs.readFileSync(settings, 'utf8').matchAll(/"id"\s*:\s*"([^"]+)"/g)) ids.add(m[1]);
  wired = ids.size;
}

const commonRules = ls(path.join(CLAUDE, 'rules', 'common'), (f) => f.endsWith('.md')).length;
const langDirs = ['python', 'rust', 'typescript'].filter((d) => isDir(path.join(CLAUDE, 'rules', d)));
const hasWeb = isDir(path.join(CLAUDE, 'rules', 'web'));
const translations = ['ja', 'id', 'zh'].filter((d) => isDir(path.join(CLAUDE, 'rules', d)));
const mcpServers = (() => {
  const p = path.join(ROOT, '.mcp.json');
  if (!fs.existsSync(p)) return 0;
  try {
    return Object.keys(JSON.parse(fs.readFileSync(p, 'utf8')).mcpServers || {}).length;
  } catch {
    return 0;
  }
})();

const body = `<!-- GENERATED by scripts/gen-asset-inventory.js — do not edit by hand. -->
<!-- Run \`node scripts/gen-asset-inventory.js\` after adding/removing assets. -->

# Asset Inventory (single source of truth)

This file is generated from the repository and verified in CI
(\`gen-asset-inventory.js --check\`). Any deck / doc / README that cites a count
MUST match the numbers here — that is how count drift (e.g. a slide still saying
"45 agents") is caught before merge.

| Asset | Count |
|-------|-------|
| Agents (\`.claude/agents/*.md\`) | ${agents} |
| Commands (\`.claude/commands/*.md\`) | ${commands} |
| Skills (\`.claude/skills/*/SKILL.md\`) | ${skills} |
| Hook scripts (\`scripts/hooks/*.js\`) | ${hookScripts} |
| Wired hooks (\`settings.json\` ids) | ${wired} |
| MCP servers (\`.mcp.json\`) | ${mcpServers} |
| Common rules (\`rules/common/*.md\`) | ${commonRules} |
| Language rule sets | ${langDirs.length} (${langDirs.join(' / ')})${hasWeb ? ' + web' : ''} |
| Translations | ${translations.length} (${translations.join(' / ')}) |

_Docs: \`docs/agent-model-master-spec.md\` (mother document), \`docs/取扱説明書.md\` — pptx decks retired 2026-08-29
cite the Agents / Skills / Hook-scripts / Wired figures above. Update them when
this inventory changes (superseded decks live in \`docs/archive/\`)._
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('[asset-inventory] STALE — docs/asset-inventory.md is out of date.');
    console.error('  Run: node scripts/gen-asset-inventory.js  (then commit)');
    process.exit(1);
  }
  console.log(`[asset-inventory] OK — up to date [agents=${agents} commands=${commands} skills=${skills} hooks=${hookScripts} wired=${wired}]`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`[asset-inventory] wrote ${path.relative(ROOT, OUT)} [agents=${agents} commands=${commands} skills=${skills} hooks=${hookScripts} wired=${wired}]`);
