test("dashboard AI progress report (single request): background job chip + completion", async ({ browser }) => {
  test.setTimeout(420_000)
  const s = readState()
  const { ctx, page, issues } = await newUserPage(browser, "po")
  await page.goto(`/projects/${s.projectId}`)
  const btn = page.getByRole("button", { name: "進捗レポート生成" })
  await expect(btn).toBeEnabled({ timeout: 20_000 })
  const resp = page.waitForResponse((r) => r.request().method() === "POST" && /ai/.test(r.url()))
  await btn.click()
  const r = await resp
  console.log("AI job start", r.request().url(), r.status(), (await r.text()).slice(0, 300))
  await expect(page.getByText(/バックグラウンドで生成中/).first()).toBeVisible({ timeout: 15_000 })
  await expect(btn).toBeDisabled()
  await shot(page, "05-ai-job-chip", false)
  const header = page.locator("main").first()
  console.log("header text after start:", (await header.innerText()).slice(0, 200).replace(/\n/g, " | "))
  // wait for completion (chip changes / button re-enabled)
  const t0 = Date.now()
  await expect(btn).toBeEnabled({ timeout: 400_000 })
  console.log("AI job finished after s:", Math.round((Date.now() - t0) / 1000))
  await page.waitForTimeout(1500)
  await shot(page, "05-ai-job-done", false)
  console.log("header text after done:", (await header.innerText()).slice(0, 300).replace(/\n/g, " | "))
  report("ai job", issues)
  await ctx.close()
})

