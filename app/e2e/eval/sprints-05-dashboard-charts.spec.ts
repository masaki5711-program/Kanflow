import { expect, test } from "@playwright/test"
import { IOT, japaneseStrings, newUserPage, readState, report, shot } from "./sprints-support"

/** Project dashboard (active sprint card, my tasks, upcoming due, activity feed, description, AI job), burndown, Gantt. */

test("dashboard (dev, id): active sprint card counts, sparkline, my tasks, upcoming, activity feed", async ({ browser }) => {
  const s = readState()
  const { ctx, page, issues } = await newUserPage(browser, "dev")
  await page.goto(`/projects/${s.projectId}`)
  const card = page.getByRole("region", { name: "E2E-Sprint-A" })
  await expect(card).toBeVisible({ timeout: 20_000 })
  const cardText = (await card.innerText()).replace(/\n/g, " | ")
  console.log("active sprint card:", cardText)
  await expect(card.getByRole("img", { name: /dari 6 tugas/ })).toBeVisible()
  // The sprint has 6 real tasks (2 done). The card must agree with the sparkline / board.
  expect.soft(cardText, "active-sprint card counts PBI placeholder rows as tasks").toMatch(/2\/6 tugas selesai/)
  // my tasks → deep link
  const mine = page.getByRole("region", { name: /Tugas saya di proyek ini/ })
  await expect(mine.getByRole("link", { name: /E2E-Task-4 docs/ })).toHaveAttribute("href", /sprints\?task=/)
  await expect(page.getByRole("region", { name: "Segera jatuh tempo" }).getByRole("link")).toContainText("E2E-Sprint-A")
  // activity feed: localized sentences + links
  const feed = page.getByRole("region", { name: "Aktivitas terbaru" })
  const firstItems = await feed.getByRole("listitem").allInnerTexts()
  console.log("feed (first 5):", JSON.stringify(firstItems.slice(0, 5)))
  const jp = await japaneseStrings(page, "main")
  console.log("JP strings on dashboard (id user):", JSON.stringify(jp))
  // description collapsed by default
  const details = page.locator("details").filter({ hasText: "Deskripsi proyek" }).filter({ hasText: "E2E sprints evaluation" }).first()
  await expect(details).not.toHaveAttribute("open", "")
  await details.locator("summary").click()
  await expect(details).toHaveAttribute("open", "")
  await expect(page.getByText("E2E sprints evaluation (cycle 2).").first()).toBeVisible()
  // feed link navigates to the sprint deep link
  await feed.getByRole("link", { name: /sprint “E2E-Sprint-A”/ }).first().click()
  await expect(page).toHaveURL(/\/sprints/)
  await expect(page.locator("[data-deep-link-highlight]")).toHaveCount(1, { timeout: 15_000 })
  report("dashboard dev", issues)
  await ctx.close()
})

