test("touch: 'move to…' menu on a phone viewport", async ({ browser }) => {
  const s = readState()
  const { ctx, page, issues } = await newUserPage(browser, "dev", { ...devices["Pixel 7"] })
  await gotoSprints(page, s.projectId, "?view=board")
  await page.waitForTimeout(1000)
  await shot(page, "02-mobile-board")
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
  console.log("page horizontal overflow px:", overflow)
  const card = cardOf(board(page), "E2E-Task-6 deploy")
  await card.getByRole("button", { name: /^Pindahkan/ }).tap()
  const menu = card.getByRole("list", { name: "Pindahkan ke" })
  await expect(menu).toBeVisible()
  await shot(page, "02-mobile-move-menu", false)
  const opts = await menu.getByRole("button").allInnerTexts()
  console.log("move options:", JSON.stringify(opts))
  expect(opts.map((o) => o.trim())).toEqual(["Sedang Berjalan", "Selesai"])
  await menu.getByRole("button", { name: "Sedang Berjalan" }).tap()
  await expect(cardOf(col(page, "Sedang Berjalan"), "E2E-Task-6 deploy")).toBeVisible()
  // a touch swipe on a card must not start a drag / change status
  await page.waitForTimeout(800)
  expect((await taskByName(page, "E2E-Task-6 deploy")).status).toBe("in_progress")
  // Selesai via menu → completion dialog
  await cardOf(board(page), "E2E-Task-6 deploy").getByRole("button", { name: /^Pindahkan/ }).tap()
  await cardOf(board(page), "E2E-Task-6 deploy").getByRole("list", { name: "Pindahkan ke" }).getByRole("button", { name: "Selesai" }).tap()
  const dlg = page.getByRole("dialog", { name: /Tugas Selesai/ })
  await expect(dlg).toBeVisible()
  await shot(page, "02-mobile-complete-dialog", false)
  await dlg.getByRole("button", { name: "Selesai tanpa komentar" }).tap()
  await expect(dlg).toBeHidden()
  await page.waitForTimeout(800)
  expect((await taskByName(page, "E2E-Task-6 deploy")).status).toBe("done")
  report("touch", issues)
  await ctx.close()
})
