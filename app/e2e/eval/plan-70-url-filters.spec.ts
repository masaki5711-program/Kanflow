import { expect, test } from "@playwright/test"
import { PROJECT, SHOTS, createItem, deleteItem, gotoPlan, patchItem, report, row, stamp, userPage, type Item } from "./plan-support"

/** URL state (?zoom=, ?item=), filters, expand/collapse persistence, 今日へ. */
test.describe.configure({ mode: "serial" })

let s = ""
let root: Item, mid: Item, deep: Item, other: Item

test.beforeAll(async ({ browser }) => {
  const { ctx, page } = await userPage(browser, "po")
  await page.goto("/")
  s = stamp()
  root = await createItem(page, { name: `E2E-U${s} ルート`, plannedStart: "2026-10-01", plannedEnd: "2026-10-20" })
  mid = await createItem(page, { name: `E2E-U${s} 中間`, parentId: root.id, plannedStart: "2026-10-01", plannedEnd: "2026-10-20" })
  deep = await createItem(page, { name: `E2E-U${s} 深い項目`, parentId: mid.id, plannedStart: "2026-10-05", plannedEnd: "2026-10-20" })
  other = await createItem(page, { name: `E2E-U${s} 別件`, plannedStart: "2026-11-01", plannedEnd: "2026-11-05" })
  await patchItem(page, other.id, { status: "on_hold" })
  await ctx.close()
})

test.afterAll(async ({ browser }) => {
  const { ctx, page } = await userPage(browser, "po")
  await page.goto("/")
  for (const it of [root, other]) await deleteItem(page, it.id)
  await ctx.close()
})

test("?zoom= in URL and zoom buttons update the URL", async ({ browser }) => {
  const { ctx, page, issues } = await userPage(browser, "po", { viewport: { width: 1440, height: 900 } })
  await gotoPlan(page, "?zoom=month")
  await expect(page.getByRole("button", { name: "月", exact: true })).toHaveAttribute("aria-pressed", "true")
  await page.getByRole("button", { name: "日", exact: true }).click()
  await expect(page).toHaveURL(/zoom=day/)
  await page.getByRole("button", { name: "週", exact: true }).click()
  await expect(page).not.toHaveURL(/zoom=/)
  await page.getByRole("button", { name: "四半期", exact: true }).click()
  await page.reload()
  await expect(page.getByRole("button", { name: "四半期", exact: true })).toHaveAttribute("aria-pressed", "true")
  await gotoPlan(page, "?zoom=bogus")
  await expect(page.getByRole("button", { name: "週", exact: true })).toHaveAttribute("aria-pressed", "true")
  // Browser back after zoom changes (replaceState → no history entries)
  report("zoom url", issues)
  await ctx.close()
})

test("?item=<id> expands collapsed ancestors and opens the editor; unknown id toasts", async ({ browser }) => {
  const { ctx, page, issues } = await userPage(browser, "po", { viewport: { width: 1440, height: 900 } })
  await gotoPlan(page)
  await page.getByRole("button", { name: "すべて折りたたむ" }).click()
  await expect(row(page, deep.id)).toHaveCount(0)
  await gotoPlan(page, `?item=${deep.id}`)
  const d = page.getByRole("dialog")
  await expect(d.getByRole("heading", { name: "計画項目を編集" })).toBeVisible()
  await expect(d.getByLabel(/項目名/)).toHaveValue(`E2E-U${s} 深い項目`)
  await expect(page).not.toHaveURL(/item=/)
  await page.keyboard.press("Escape")
  await expect(row(page, deep.id)).toBeVisible()
  await expect(row(page, deep.id)).toHaveAttribute("data-selected", "true")
  await page.screenshot({ path: `${SHOTS}/70-item-deeplink.png` })
  await gotoPlan(page, "?item=doesnotexist123")
  await expect(page.getByText("指定された計画項目が見つかりません")).toBeVisible()
  await page.screenshot({ path: `${SHOTS}/71-item-unknown.png` })
  report("item param", issues)
  await ctx.close()
})

test("filters: text / state / owner, count, clear, no-match state", async ({ browser }) => {
  const { ctx, page, issues } = await userPage(browser, "po", { viewport: { width: 1440, height: 900 } })
  await gotoPlan(page)
  await page.getByRole("button", { name: "すべて展開" }).click()
  const search = page.getByRole("searchbox", { name: "項目名で絞り込み" })
  await search.fill(`E2E-U${s} 深い`)
  await expect(row(page, deep.id)).toBeVisible()
  await expect(row(page, root.id)).toBeVisible() // ancestors kept for context
  await expect(row(page, other.id)).toHaveCount(0)
  const status = page.locator('[role="search"] [role="status"]')
  console.log("filter count:", await status.innerText())
  await page.screenshot({ path: `${SHOTS}/72-filter-text.png` })
  await page.getByRole("button", { name: "絞り込みを解除" }).click()
  await expect(search).toHaveValue("")
  await page.getByLabel("状態").selectOption({ label: "保留" })
  await expect(row(page, other.id)).toBeVisible()
  await expect(row(page, deep.id)).toHaveCount(0)
  await page.getByLabel("状態").selectOption({ label: "すべて" })
  await page.getByLabel("担当者").selectOption({ label: "E2E PO" })
  const ownerRows = await page.locator("[data-plan-row]").count()
  console.log("owner=E2E PO rows:", ownerRows)
  await search.fill("zzzz-no-match")
  await expect(page.getByText("条件に一致する項目はありません")).toBeVisible()
  await page.screenshot({ path: `${SHOTS}/73-filter-empty.png` })
  await page.getByRole("button", { name: "絞り込みを解除" }).first().click()
  // Filters are not persisted: reload resets
  await search.fill(`E2E-U${s}`)
  await page.reload()
  await expect(page.getByRole("searchbox", { name: "項目名で絞り込み" })).toHaveValue("")
  report("filters", issues)
  await ctx.close()
})

test("collapse persists across reload; 今日へ scrolls back to today", async ({ browser }) => {
  const { ctx, page, issues } = await userPage(browser, "po", { viewport: { width: 1440, height: 900 } })
  await gotoPlan(page)
  await page.getByRole("button", { name: "すべて展開" }).click()
  await expect(row(page, deep.id)).toBeVisible()
  await page.getByRole("button", { name: `折りたたむ: E2E-U${s} ルート` }).click()
  await expect(row(page, mid.id)).toHaveCount(0)
  await page.reload()
  await expect(row(page, root.id)).toBeVisible()
  await expect(row(page, mid.id)).toHaveCount(0)
  await page.getByRole("button", { name: "すべて展開" }).click()
  await expect(row(page, deep.id)).toBeVisible()
  // 今日へ
  const chart = page.locator("[data-plan-chart]")
  const initial = await chart.evaluate((e) => e.scrollLeft)
  await chart.evaluate((e) => { e.scrollLeft = 0 })
  await page.getByRole("button", { name: "今日へ" }).click()
  const back = await chart.evaluate((e) => e.scrollLeft)
  console.log("scrollLeft initial/after 今日へ:", initial, back)
  expect(Math.abs(back - initial)).toBeLessThan(3)
  report("collapse", issues)
  await ctx.close()
})
