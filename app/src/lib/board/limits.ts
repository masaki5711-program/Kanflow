/**
 * ボード (docs/plan/10-board.md): the bounds of everything a client may send. One place, shared by the
 * request schemas (server) and the editor (client), so the editor never offers what the server refuses.
 */
export const BOARD_LIMITS = {
  /** Live boards per project. */
  boardsPerProject: 200,
  sheetsPerBoard: 30,
  /** Live elements per sheet (plan §6: a large sheet stays fast up to a few thousand elements). */
  elementsPerSheet: 5000,
  /** Elements in one write request; the editor sends more in several requests. */
  elementsPerWrite: 500,
  /** Body of one write request, in bytes. */
  writeBodyBytes: 2 * 1024 * 1024,
  /** JSON text of one element's `data`, in characters. */
  elementJsonChars: 16 * 1024,
  /** Characters of an element's text. */
  textLength: 4000,
  titleLength: 120,
  sheetNameLength: 60,
  /** |x|, |y| of any point. */
  coordinate: 1_000_000,
  /** Width / height of a box. */
  boxSize: 100_000,
  /** Highest element version / z value accepted. */
  counter: 2_000_000_000,
} as const

/** Element ids are generated by the client; the server only checks the shape. */
export const ELEMENT_ID_PATTERN = /^[A-Za-z0-9_-]{6,40}$/

/** `type` of an element this build does not know (kept untouched). */
export const ELEMENT_TYPE_PATTERN = /^[a-z][a-z0-9_-]{0,31}$/
